#include "lcd1602.h"
#include "delay.h"

#define LCD1602_DB0_PIN GPIO_PIN_0
#define LCD1602_DB0_GPIO_PORT GPIOB
#define LCD1602_DB1_PIN GPIO_PIN_1
#define LCD1602_DB1_GPIO_PORT GPIOB
#define LCD1602_DB2_PIN GPIO_PIN_2
#define LCD1602_DB2_GPIO_PORT GPIOB
#define LCD1602_DB3_PIN GPIO_PIN_3
#define LCD1602_DB3_GPIO_PORT GPIOB
#define LCD1602_DB4_PIN GPIO_PIN_4
#define LCD1602_DB4_GPIO_PORT GPIOB
#define LCD1602_DB5_PIN GPIO_PIN_5
#define LCD1602_DB5_GPIO_PORT GPIOB
#define LCD1602_DB6_PIN GPIO_PIN_6
#define LCD1602_DB6_GPIO_PORT GPIOB
#define LCD1602_DB7_PIN GPIO_PIN_7
#define LCD1602_DB7_GPIO_PORT GPIOB
#define LCD1602_RS_PIN GPIO_PIN_8
#define LCD1602_RS_GPIO_PORT GPIOB
#define LCD1602_RW_PIN GPIO_PIN_9
#define LCD1602_RW_GPIO_PORT GPIOB
#define LCD1602_E_PIN GPIO_PIN_10
#define LCD1602_E_GPIO_PORT GPIOB

#define LCD1602_DB0_CLK_ENABLE() __HAL_RCC_GPIOB_CLK_ENABLE()
#define LCD1602_DB1_CLK_ENABLE() __HAL_RCC_GPIOB_CLK_ENABLE()
#define LCD1602_DB2_CLK_ENABLE() __HAL_RCC_GPIOB_CLK_ENABLE()
#define LCD1602_DB3_CLK_ENABLE() __HAL_RCC_GPIOB_CLK_ENABLE()
#define LCD1602_DB4_CLK_ENABLE() __HAL_RCC_GPIOB_CLK_ENABLE()
#define LCD1602_DB5_CLK_ENABLE() __HAL_RCC_GPIOB_CLK_ENABLE()
#define LCD1602_DB6_CLK_ENABLE() __HAL_RCC_GPIOB_CLK_ENABLE()
#define LCD1602_DB7_CLK_ENABLE() __HAL_RCC_GPIOB_CLK_ENABLE()
#define LCD1602_RS_CLK_ENABLE() __HAL_RCC_GPIOB_CLK_ENABLE()
#define LCD1602_RW_CLK_ENABLE() __HAL_RCC_GPIOB_CLK_ENABLE()
#define LCD1602_E_CLK_ENABLE() __HAL_RCC_GPIOB_CLK_ENABLE()

#define LCD1602_DATA_PORT GPIOB
#define LCD1602_DATA_PIN (GPIO_PIN_0 | GPIO_PIN_1 | GPIO_PIN_2 | GPIO_PIN_3 | GPIO_PIN_4 | GPIO_PIN_5 | GPIO_PIN_6 | GPIO_PIN_7)

void LCD1602_Init(void)
{
    // 启用GPIOB时钟
    LCD1602_DB0_CLK_ENABLE();
    LCD1602_DB1_CLK_ENABLE();
    LCD1602_DB2_CLK_ENABLE();
    LCD1602_DB3_CLK_ENABLE();
    LCD1602_DB4_CLK_ENABLE();
    LCD1602_DB5_CLK_ENABLE();
    LCD1602_DB6_CLK_ENABLE();
    LCD1602_DB7_CLK_ENABLE();
    LCD1602_RS_CLK_ENABLE();
    LCD1602_RW_CLK_ENABLE();
    LCD1602_E_CLK_ENABLE();

    GPIO_InitTypeDef GPIO_InitStruct = {0};

    // 初始化数据线
    GPIO_InitStruct.Pin = LCD1602_DATA_PIN;
    GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
    GPIO_InitStruct.Pull = GPIO_NOPULL;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;
    HAL_GPIO_Init(LCD1602_DATA_PORT, &GPIO_InitStruct);

    // 初始化控制线
    GPIO_InitStruct.Pin = LCD1602_RS_PIN | LCD1602_RW_PIN | LCD1602_E_PIN;
    GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
    GPIO_InitStruct.Pull = GPIO_NOPULL;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;
    HAL_GPIO_Init(GPIOB, &GPIO_InitStruct);

    // 初始化LCD
    delay_ms(15); // 等待LCD初始化
    LCD1602_WriteCommand(0x33); // 功能设置：16位数据接口，两行显示，5x8点阵
    LCD1602_WriteCommand(0x32); // 功能设置：16位数据接口，两行显示，5x8点阵
    LCD1602_WriteCommand(0x28); // 功能设置：4位数据接口，两行显示，5x8点阵
    LCD1602_WriteCommand(0x0C); // 显示开，光标关，闪烁关
    LCD1602_WriteCommand(0x06); // 写一个字符指针加1
    LCD1602_WriteCommand(0x01); // 清屏
    delay_ms(5);
}

void LCD1602_WriteCommand(uint8_t cmd)
{
    // 设置为命令模式
    HAL_GPIO_WritePin(LCD1602_RS_GPIO_PORT, LCD1602_RS_PIN, GPIO_PIN_RESET);
    HAL_GPIO_WritePin(LCD1602_RW_GPIO_PORT, LCD1602_RW_PIN, GPIO_PIN_RESET);

    // 写入高4位
    HAL_GPIO_WritePin(LCD1602_DATA_PORT, LCD1602_DATA_PIN, (cmd >> 4) & 0x0F);
    HAL_GPIO_WritePin(LCD1602_E_GPIO_PORT, LCD1602_E_PIN, GPIO_PIN_SET);
    delay_ms(1);
    HAL_GPIO_WritePin(LCD1602_E_GPIO_PORT, LCD1602_E_PIN, GPIO_PIN_RESET);

    // 写入低4位
    HAL_GPIO_WritePin(LCD1602_DATA_PORT, LCD1602_DATA_PIN, cmd & 0x0F);
    HAL_GPIO_WritePin(LCD1602_E_GPIO_PORT, LCD1602_E_PIN, GPIO_PIN_SET);
    delay_ms(1);
    HAL_GPIO_WritePin(LCD1602_E_GPIO_PORT, LCD1602_E_PIN, GPIO_PIN_RESET);

    delay_ms(1);
}

void LCD1602_WriteData(uint8_t data)
{
    // 设置为数据模式
    HAL_GPIO_WritePin(LCD1602_RS_GPIO_PORT, LCD1602_RS_PIN, GPIO_PIN_SET);
    HAL_GPIO_WritePin(LCD1602_RW_GPIO_PORT, LCD1602_RW_PIN, GPIO_PIN_RESET);

    // 写入高4位
    HAL_GPIO_WritePin(LCD1602_DATA_PORT, LCD1602_DATA_PIN, (data >> 4) & 0x0F);
    HAL_GPIO_WritePin(LCD1602_E_GPIO_PORT, LCD1602_E_PIN, GPIO_PIN_SET);
    delay_ms(1);
    HAL_GPIO_WritePin(LCD1602_E_GPIO_PORT, LCD1602_E_PIN, GPIO_PIN_RESET);

    // 写入低4位
    HAL_GPIO_WritePin(LCD1602_DATA_PORT, LCD1602_DATA_PIN, data & 0x0F);
    HAL_GPIO_WritePin(LCD1602_E_GPIO_PORT, LCD1602_E_PIN, GPIO_PIN_SET);
    delay_ms(1);
    HAL_GPIO_WritePin(LCD1602_E_GPIO_PORT, LCD1602_E_PIN, GPIO_PIN_RESET);

    delay_ms(1); // 添加括号和参数
}